// ModelledValueHeads returns a copy of the modelled count-head list.
func ModelledValueHeads() []string {
	return append([]string(nil), modelledValueHeads...)
}

func init() {
	prefixed := make([]string, len(modelledValueHeads))
	for i, h := range modelledValueHeads {
		prefixed[i] = cards.ValueHeadPrefix + h
	}
	RegisterNonAPI(prefixed...)
}
