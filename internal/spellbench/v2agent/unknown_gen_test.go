// unknown_gen.go is generated from the Go request types by genUnknownSchema,
// with the reflective walk's own rules (unknown_reflect_test.go: pointers
// dereferenced, json.RawMessage opaque, embedded structs flattened).
// TestUnknownSchemaIsCurrent fails when a request type changes without a
// regeneration:
//
//	UNKNOWN_REGEN=1 go test ./internal/spellbench/v2agent -run TestUnknownSchemaIsCurrent

const unknownGenFile = "unknown_gen.go"

var unknownGenRoots = []struct {
	name string
	typ  reflect.Type
}{
	{"GameStart", reflect.TypeFor[GameStart]()},
	{"GameStartRequest", reflect.TypeFor[gameStartRequest]()},
	{"Semantic", reflect.TypeFor[Semantic]()},
	{"SeatDecision", reflect.TypeFor[SeatDecision]()},
}

func genUnknownSchema() ([]byte, error) {
	type node struct {
		kind   string
		elem   int
		fields [][2]any
	}
	var nodes []node
	index := map[reflect.Type]int{}
	var build func(t reflect.Type) int
	build = func(t reflect.Type) int {
		for t != nil && t.Kind() == reflect.Pointer {
			t = t.Elem()
		}
		if i, ok := index[t]; ok {
			return i
		}
		i := len(nodes)
		index[t] = i
		nodes = append(nodes, node{kind: "unknownOpaque"})
		if t == rawMessageType {
			return i
		}
		switch t.Kind() {
		case reflect.Struct:
			fs := jsonFields(t)
			names := make([]string, 0, len(fs))
			for k := range fs {
				names = append(names, k)
			}
			sort.Strings(names)
			nodes[i].kind = "unknownObject"
			var fields [][2]any
			for _, k := range names {
				fields = append(fields, [2]any{k, build(fs[k])})
			}
			nodes[i].fields = fields
		case reflect.Slice, reflect.Array:
			e := build(t.Elem())
			nodes[i].kind, nodes[i].elem = "unknownList", e
		case reflect.Map:
			e := build(t.Elem())
			nodes[i].kind, nodes[i].elem = "unknownMap", e
		}
		return i
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by genUnknownSchema (unknown_gen_test.go); DO NOT EDIT.\n\npackage v2agent\n\n")
	roots := make([]int, len(unknownGenRoots))
	for i, r := range unknownGenRoots {
		roots[i] = build(r.typ)
	}
	b.WriteString("const (\n")
	for i, r := range unknownGenRoots {
		fmt.Fprintf(&b, "unknownRoot%s int32 = %d\n", r.name, roots[i])
	}
	b.WriteString(")\n\nvar unknownNodes = [...]unknownNode{\n")
	for i, n := range nodes {
		fmt.Fprintf(&b, "%d: {kind: %s", i, n.kind)
		if n.kind == "unknownList" || n.kind == "unknownMap" {
			fmt.Fprintf(&b, ", elem: %d", n.elem)
		}
		if n.kind == "unknownObject" {
			b.WriteString(", fields: []unknownField{")
			for _, f := range n.fields {
				fmt.Fprintf(&b, "{%q, %d}, ", f[0], f[1])
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func TestUnknownSchemaIsCurrent(t *testing.T) {
	want, err := genUnknownSchema()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("UNKNOWN_REGEN") == "1" {
		if err := os.WriteFile(unknownGenFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(unknownGenFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale against the request types: regenerate with UNKNOWN_REGEN=1 go test ./internal/spellbench/v2agent -run TestUnknownSchemaIsCurrent", unknownGenFile)
	}
}

// checkUnknownOracle requires the generated-schema UnknownFields to report
// exactly the reflective walk's paths on raw, and on raw with an unknown key
// planted in every JSON object it contains (so every node's field set is
// exercised, not only the all-known case).
func checkUnknownOracle(t *testing.T, label string, raw []byte, target any) {
	t.Helper()
	v, err := decodeAny(raw)
	if err != nil {
		return
	}
	var plant func(v any) any
	plant = func(v any) any {
		switch x := v.(type) {
		case map[string]any:
			for k, e := range x {
				x[k] = plant(e)
			}
			x["zz_planted"] = true
		case []any:
			for i := range x {
				x[i] = plant(x[i])
			}
		}
		return v
	}
	planted, err := json.Marshal(plant(v))
	if err != nil {
		t.Fatal(err)
	}
	for i, in := range [][]byte{raw, planted} {
		got, want := UnknownFields(in, target), reflectUnknownFields(in, target)
		if i == 1 && len(want) == 0 {
			t.Fatalf("%s: the planted document reports no unknown field", label)
		}
		if !slices.Equal(got, want) {
			t.Fatalf("%s: UnknownFields %v, reflective walk %v", label, got, want)
		}
	}
}

// TestUnknownFieldsIsReflective: on a planted document per root type the
// generated walk reports the reflective walk's paths.
func TestUnknownFieldsIsReflective(t *testing.T) {
	doc := []byte(`{"a":1,"decision":{"x":[{"y":2}]},"candidates":[{"semantic":{"k":1},"q":[1]}],"observation":{"players":[{"z":1}],"extensions":{"e":{"f":1}}},"own_deck":[{"name":"x","w":1}]}`)
	checkUnknownOracle(t, "GameStart", doc, &GameStart{})
	checkUnknownOracle(t, "GameStartRequest", doc, &gameStartRequest{})
	checkUnknownOracle(t, "Semantic", doc, &Semantic{})
	checkUnknownOracle(t, "SeatDecision", doc, &SeatDecision{})
}
